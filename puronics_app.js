function calculateSavings() {
    const familySize = parseInt(document.getElementById('inputFamilySize')?.value || 4);
    const monthlyBottledSpend = parseFloat(document.getElementById('inputBottledSpend')?.value || 80);

    const annualBottledSavings = monthlyBottledSpend * 12;
    const annualDetergentSavings = familySize * 95;
    const totalAnnualSavings = annualBottledSavings + annualDetergentSavings;
    const bottlesEliminated = familySize * 1050;

    const numEl = document.getElementById('calcAnnualSavings');
    const bottleEl = document.getElementById('calcBottlesEliminated');

    if (numEl) numEl.innerText = `$${totalAnnualSavings.toLocaleString()}`;
    if (bottleEl) {
        bottleEl.innerText = currentLang === 'es'
            ? `${bottlesEliminated.toLocaleString()} botellas de plástico eliminadas/año`
            : `${bottlesEliminated.toLocaleString()} plastic bottles eliminated/year`;
    }
}

