function playAmbientMusic() {
    try {
        if (!audioCtx) {
            audioCtx = new (window.AudioContext || window.webkitAudioContext)();
        }
        if (audioCtx.state === 'suspended') {
            audioCtx.resume();
        }

        stopAmbientMusic();

        gainNode = audioCtx.createGain();
        gainNode.gain.setValueAtTime(0.038, audioCtx.currentTime);

        const frequencies = [216.00, 324.00, 432.00, 540.00];

        frequencies.forEach((freq, idx) => {
            const osc = audioCtx.createOscillator();
            const oscGain = audioCtx.createGain();

            osc.type = idx % 2 === 0 ? 'sine' : 'triangle';
            osc.frequency.setValueAtTime(freq, audioCtx.currentTime);

            const vol = idx === 0 ? 0.35 : 0.22;
            oscGain.gain.setValueAtTime(vol, audioCtx.currentTime);

            osc.connect(oscGain);
            oscGain.connect(gainNode);
            osc.start();

            activeOscillators.push(osc);
        });
    } catch (err) {
        console.log("Audio Context Error:", err);
    }
}

function stopAmbientMusic() {
    if (activeOscillators && activeOscillators.length > 0) {
        activeOscillators.forEach(osc => {
            try {
                osc.stop();
                osc.disconnect();
            } catch (e) {}
        });
        activeOscillators = [];
    }
    if (gainNode) {
        try {
            gainNode.disconnect();
        } catch (e) {}
        gainNode = null;
    }
}

