// SLIDE NAVIGATION FUNCTIONS
function nextSlide() {
    const list = benefitsData[currentLang];
    currentIndex = (currentIndex + 1) % list.length;
    updateSlide();
}

function prevSlide() {
    const list = benefitsData[currentLang];
    currentIndex = (currentIndex - 1 + list.length) % list.length;
    updateSlide();
}

function jumpToSlide(index) {
    currentIndex = index;
    updateSlide();
}

function toggleAutoPlay() {
    const btn = document.getElementById('btnAutoPlay');
    if (isPlaying) {
        isPlaying = false;
        if (autoPlayTimer) clearInterval(autoPlayTimer);
        autoPlayTimer = null;
        if (btn) {
            btn.innerHTML = '▶ Autoplay';
            btn.classList.remove('active');
        }
    } else {
        isPlaying = true;
        if (btn) {
            btn.innerHTML = '⏸ Pausar Autoplay';
            btn.classList.add('active');
        }
        autoPlayTimer = setInterval(() => {
            nextSlide();
        }, 5000);
    }
}

function toggleVoiceover() {
    const btn = document.getElementById('btnVoiceover');
    const synth = window.speechSynthesis;
    
    if (voiceoverEnabled) {
        voiceoverEnabled = false;
        if (btn) btn.classList.remove('active', 'voiceover-active');
        if (synth) synth.cancel();
    } else {
        stopAllOtherAudio('voiceover');
        voiceoverEnabled = true;
        if (btn) btn.classList.add('active', 'voiceover-active');

        if (synth) {
            synth.cancel();
            if (synth.paused) synth.resume();
        }

        const item = benefitsData[currentLang][currentIndex];
        if (item) {
            const fullSpeechText = currentLang === 'es'
                ? `Beneficio número ${item.id}: ${item.title}. ${item.description} ${item.highlight}`
                : `Benefit number ${item.id}: ${item.title}. ${item.description} ${item.highlight}`;
            speakText(fullSpeechText);
        }
    }
}

function speakText(text) {
    const synth = window.speechSynthesis;
    if (!synth) return;

    try {
        synth.cancel();
        if (synth.paused) synth.resume();

        const utterance = new SpeechSynthesisUtterance(text);
        utterance.lang = currentLang === 'es' ? 'es-US' : 'en-US';
        utterance.rate = 0.96;
        utterance.pitch = 1.0;
        utterance.volume = 1.0;

        const voices = synth.getVoices();
        if (voices && voices.length > 0) {
            const targetLang = currentLang === 'es' ? 'es' : 'en';
            const matchedVoice = voices.find(v => v.lang && v.lang.toLowerCase().startsWith(targetLang));
            if (matchedVoice) utterance.voice = matchedVoice;
        }

        utterance.onend = () => {
            if (voiceoverEnabled && !coverVidAudioEnabled && !commercialPlaying) {
                setTimeout(() => {
                    if (voiceoverEnabled && !coverVidAudioEnabled && !commercialPlaying) {
                        nextSlide();
                    }
                }, 2000);
            }
        };

        utterance.onerror = (e) => {
            console.warn("Speech error:", e);
        };

        synth.speak(utterance);
    } catch (err) {
        console.error("speakText Exception:", err);
    }
}

function updateSlide() {
    const list = benefitsData[currentLang];
    const item = list[currentIndex];

    const graphic = document.getElementById('slideGraphic');
    const badge = document.getElementById('slideBadge');
    const techTag = document.getElementById('slideTechTag');
    const title = document.getElementById('slideTitle');
    const desc = document.getElementById('slideDescription');
    const highlight = document.getElementById('slideHighlight');
    const counterText = document.getElementById('slideCounterText');
    const progressFill = document.getElementById('progressBarFill');

    if (graphic) {
        graphic.innerHTML = item.icon;
        graphic.classList.remove('graphic-transition-in');
        void graphic.offsetWidth;
        graphic.classList.add('graphic-transition-in');
    }

    if (badge) badge.innerText = item.badge;
    if (techTag) techTag.innerText = item.techTag;
    if (title) title.innerText = item.title;
    if (desc) desc.innerText = item.description;
    if (highlight) highlight.innerText = item.highlight;

    const textInfo = document.getElementById('slideTextInfo');
    if (textInfo) {
        textInfo.classList.remove('slide-transition-in');
        void textInfo.offsetWidth;
        textInfo.classList.add('slide-transition-in');
    }

    if (counterText) {
        counterText.innerText = currentLang === 'es' 
            ? `Diapositiva ${currentIndex + 1} de ${list.length}` 
            : `Slide ${currentIndex + 1} of ${list.length}`;
    }

    if (progressFill) {
        const percent = ((currentIndex + 1) / list.length) * 100;
        progressFill.style.width = `${percent}%`;
    }

    const cards = document.querySelectorAll('.benefit-card');
    cards.forEach((card, idx) => {
        if (idx === currentIndex) {
            card.classList.add('active');
        } else {
            card.classList.remove('active');
        }
    });

    if (voiceoverEnabled && !coverVidAudioEnabled) {
        const fullSpeechText = currentLang === 'es'
            ? `Beneficio número ${item.id}: ${item.title}. ${item.description} ${item.highlight}`
            : `Benefit number ${item.id}: ${item.title}. ${item.description} ${item.highlight}`;
        speakText(fullSpeechText);
    }
}

